import assert from 'node:assert/strict';
import {publicationFields} from '../src/release-backend/kadr-madar-release/publication-fields.mjs';
import {publicReleaseReady} from '../src/release-backend/kadr-release-watcher/public-release-ready.mjs';
const owner={id:'owner',role:'admin',is_active:true},current={stable_revision:1192};
const proof={version:'1.23',commitSha:'cfee9408f97f1172b3e1f5744732329a798e04e9',iat:1793725575,dryRun:false,notes:'Approved release'};
const p=publicationFields(proof,current,owner,'2026-11-03T17:20:00Z');
assert.equal(p.candidate_approved_by,owner.id);assert.equal(p.stable_published_by,owner.id);
assert.equal(p.candidate_approved_at,new Date(proof.iat*1000).toISOString());
assert.equal(p.stable_version,p.candidate_version);assert.equal(p.stable_revision,1193);
assert.equal(p.stable_git_sha,proof.commitSha);assert.equal(p.candidate_status,'published');
assert.equal(p.candidate_available,false);assert.equal(p.candidate_tested_at,undefined);
for(const invalid of [null,{...owner,is_active:false},{...owner,role:'creator'}])assert.throws(()=>publicationFields(proof,current,invalid));
assert.throws(()=>publicationFields({...proof,dryRun:true},current,owner));
assert.throws(()=>publicationFields({...proof,commitSha:'bad'},current,owner));
const names=['index.html','app.js','app.css','config.js','manifest.webmanifest','sw.js'];
const texts=Object.fromEntries(names.map(n=>[n,'source '+n]));let calls=0;
const good=async(url,opts)=>{calls++;assert.equal(opts.redirect,'error');assert(url.startsWith('https://irumaithy.github.io/KADR/releases/v1.23/'));const file=new URL(url).pathname.split('/').at(-1);return {ok:true,text:async()=>texts[file]}};
assert.equal(await publicReleaseReady('1.23',texts,good),true);assert.equal(calls,6);
assert.equal(await publicReleaseReady('1.23',texts,async()=>({ok:false})),false);
assert.equal(await publicReleaseReady('1.23',texts,async()=>({ok:true,text:async()=>'old content'})),false);
assert.equal(await publicReleaseReady('1.23',texts,async()=>{throw Error('network')}),false);
assert.equal(await publicReleaseReady('../bad',texts,good),false);
assert.equal(await publicReleaseReady('1.23',{},good),false);
console.log('PASS: signed approval audit fields, owner identity, fail-closed mapping, complete public assets, missing/stale/offline assets, invalid versions.');
